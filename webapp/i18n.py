def tr(lang, key, **kwargs):
    lang = lang if lang in I18N else "ar"
    text = I18N.get(lang, I18N["ar"]).get(key)
    if text is None:
        text = _(lang, key)
    try:
        return text.format(**kwargs) if kwargs else text
    except Exception:
        return text


def _(lang, text, **kwargs):
    """Translate an Arabic UI phrase; Arabic mode returns the source text."""
    if text is None:
        return ""
    text = str(text)
    if (lang or "ar") != "en":
        out = text
    else:
        out = PHRASE_EN.get(text, text)
    if kwargs:
        try:
            return out.format(**kwargs)
        except Exception:
            return out
    return out


def tv(lang, value):
    """Translate a stored list/status value for display only."""
    if value is None or value == "":
        return value
    value = str(value)
    if (lang or "ar") != "en":
        return value
    return VALUE_EN.get(value, PHRASE_EN.get(value, value))


