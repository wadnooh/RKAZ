def tr(lang, key, **kwargs):
    lang = lang if lang in I18N else "ar"
    text = I18N.get(lang, I18N["ar"]).get(key)
    if text is None:
        text = _(lang, key)
    try:
        return text.format(**kwargs) if kwargs else text
    except Exception:
        return text


def _(lang, text, **kwargs):
    """Translate an Arabic UI phrase; Arabic mode returns the source text."""
    if text is None:
        return ""
    text = str(text)
    if (lang or "ar") != "en":
        out = text
    else:
        out = PHRASE_EN.get(text, text)
    if kwargs:
        try:
            return out.format(**kwargs)
        except Exception:
            return out
    return out


def tv(lang, value):
    """Translate a stored list/status value for display only."""
    if value is None or value == "":
        return value
    value = str(value)
    if (lang or "ar") != "en":
        return value
    return VALUE_EN.get(value, PHRASE_EN.get(value, value))


def localize_module(module, lang):
    """Return module dict with title/field labels in the active language."""
    if not module or (lang or "ar") == "ar":
        return module
    m = deepcopy(module)
    m["title"] = _(lang, m.get("title") or "")
    fields = []
    for item in m.get("fields") or []:
        if len(item) >= 3:
            key, label, ftype = item[0], item[1], item[2]
            fields.append((key, _(lang, label), ftype))
        else:
            fields.append(item)
    m["fields"] = fields
    return m


def localize_section_meta(meta, lang):
    if not meta or (lang or "ar") == "ar":
        return meta
    m = dict(meta)
    if "title" in m:
        m["title"] = _(lang, m["title"])
    return m


def localize_jump(items, lang):
    if (lang or "ar") == "ar":
        return items
    out = []
    for it in items:
        row = dict(it)
        row["title"] = _(lang, row.get("title") or "")
        row["group"] = _(lang, row.get("group") or "")
        out.append(row)
    return out


